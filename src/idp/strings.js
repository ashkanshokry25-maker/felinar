export const STRINGS = Object.freeze({ en: Object.freeze(EN), fr: Object.freeze(FR) });

/** pickLang(tag) -> 'fr' when the language tag starts with fr, else 'en'. */
export function pickLang(tag) {
  return typeof tag === 'string' && /^fr\b/i.test(tag.trim()) ? 'fr' : 'en';
}

/** fmt(template, params) fills {name} with String(params[name]); unknown names stay as they are. */
export function fmt(template, params) {
  if (!params) return template;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(params, k) ? String(params[k]) : m));
}

/** t(key, params, lang) -> the string in lang (English when missing there). Unknown keys throw. */
export function t(key, params, lang = 'en') {
  const table = STRINGS[lang] || STRINGS.en;
  const s = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : STRINGS.en[key];
  if (typeof s !== 'string') throw new Error('idp strings: unknown key ' + key);
  return fmt(s, params);
}

/** errorText(code, lang) -> a sentence for an error code (a generic one for unknown codes). */
export function errorText(code, lang = 'en') {
  const table = ERRORS[lang] || ERRORS.en;
  return table[code] || ERRORS.en[code] || table.E_INTERNAL;
}

