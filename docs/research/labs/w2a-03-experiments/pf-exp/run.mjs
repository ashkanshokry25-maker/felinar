import { chromium } from '$HOME/Documents/Projects/magnet-web/node_modules/playwright/index.mjs';
import { spawn } from 'node:child_process';
const root = process.argv[2]; const mode = process.argv[3] || 'octet';
const server = spawn(process.execPath, [new URL('./server.mjs', import.meta.url).pathname, root, mode], { stdio: ['ignore', 'pipe', 'inherit'] });
const port = await new Promise((res) => server.stdout.on('data', (d) => { const m = /PORT (\d+)/.exec(String(d)); if (m) res(m[1]); }));
const base = `http://localhost:${port}`;
console.log('server port', port);
const browser = await chromium.launch({ headless: true });
console.log('launched');
const ctx = await browser.newContext();
const page = await ctx.newPage();
page.setDefaultTimeout(25000);
setTimeout(() => { console.log('HARD TIMEOUT'); process.exit(2); }, 90000);
page.on('console', (m) => { if (['warning', 'error'].includes(m.type())) console.log('console.' + m.type(), m.text().slice(0, 240)); });
page.on('pageerror', (e) => console.log('pageerror', e.message.slice(0, 240)));
console.log('goto');
await page.goto(base + '/');
console.log('loaded');
await page.waitForSelector('#site');
const frame = await (await page.$('#site')).contentFrame();
await frame.waitForFunction(() => window.__result, null, { timeout: 30000 });
const result = await frame.evaluate(() => window.__result);
const logs = await (await fetch(base + '/__log')).json();
const by = {};
for (const [f, n] of logs) { const k = f.includes('/') ? f.split('/')[0] + '/' : (f.split('.').pop()); by[k] = by[k] || { files: 0, bytes: 0 }; by[k].files++; by[k].bytes += n; }
console.log('MODE', mode, 'browser', browser.version());
console.log(JSON.stringify({ steps: result.steps, error: result.error }, null, 1));
console.log('server-side file fetches (unique files, bytes) grouped:', JSON.stringify(by));
console.log('total unique files fetched:', new Set(logs.map((l) => l[0])).size, 'total bytes', logs.reduce((a, l) => a + l[1], 0));
await browser.close(); server.kill();
